import pandas as pd
from sklearn.model_selection import StratifiedKFold
from google.colab import files
import numpy as np

file_path = '/content/drive/My Drive/Dataset2Use_Assignment1.xlsx'
data = pd.read_excel(file_path)

# Επιλογή δεδομένων από στήλες Α έως Η και ετικέτες
X = data.iloc[:, :8]
y = data["ΕΝΔΕΙΞΗ ΑΣΥΝΕΠΕΙΑΣ (=2) (ν+1)"]

# Ορισμός του Stratified K-Fold
skf = StratifiedKFold(n_splits=4, shuffle=True, random_state=42)

# Δημιουργία των τεσσάρων folds
fold = 1
for train_index, test_index in skf.split(X, y):
    # Χωρισμός δεδομένων σε train και test
    X_train, X_test = X.iloc[train_index], X.iloc[test_index]
    y_train, y_test = y.iloc[train_index], y.iloc[test_index]

    # Μέτρηση υγιών και χρεοκοπημένων εταιρειών στο train set
    train_healthy_indices = y_train[y_train == 1].index
    train_bankrupt_indices = y_train[y_train == 2].index

    # Αν η αναλογία υπερβαίνει το 3:1, αφαιρούμε υγιείς εταιρείες
    if len(train_healthy_indices) > 3 * len(train_bankrupt_indices):
        num_to_keep = 3 * len(train_bankrupt_indices)  # Υγιείς που πρέπει να κρατήσουμε
        # Επιλέγουμε τυχαία τις υγιείς εταιρείες που θα παραμείνουν
        selected_healthy_indices = np.random.choice(train_healthy_indices, num_to_keep, replace=False)
        # Δημιουργούμε το νέο train set
        new_train_indices = list(selected_healthy_indices) + list(train_bankrupt_indices)
        X_train = X_train.loc[new_train_indices]
        y_train = y_train.loc[new_train_indices]

    # Υπολογισμός νέων κατανομών
    train_healthy = (y_train == 1).sum()
    train_bankrupt = (y_train == 2).sum()
    test_healthy = (y_test == 1).sum()
    test_bankrupt = (y_test == 2).sum()

    # Εκτύπωση αποτελεσμάτων
    print(f"Fold {fold}:")
    print(f"Training Set: ")
    print(f"Υγιείς Εταιρείες: {train_healthy}, Χρεοκοπημένες Εταιρείες: {train_bankrupt}")
