import pandas as pd
import numpy as np
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import confusion_matrix, accuracy_score, precision_score, recall_score, f1_score, roc_auc_score, roc_curve
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVC
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.utils import resample

from google.colab import files


file_path = '/content/drive/My Drive/Dataset2Use_Assignment1.xlsx'
data = pd.read_excel(file_path)

# Επιλογή χαρακτηριστικών και στόχου
X = data.iloc[:, :8]
y = data["ΕΝΔΕΙΞΗ ΑΣΥΝΕΠΕΙΑΣ (=2) (ν+1)"]  # Στόχος (1=Υγιής, 2=Χρεωκοπημένη)

# Standardize τα δεδομένα
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Ορισμός του StratifiedKFold
skf = StratifiedKFold(n_splits=4, shuffle=True, random_state=42)

# Δημιουργία των μοντέλων
models = {
    "Linear Discriminant Analysis": LinearDiscriminantAnalysis(),
    "Logistic Regression": LogisticRegression(max_iter=1000, random_state=42),
    "Decision Tree": DecisionTreeClassifier(random_state=42),
    "Random Forest": RandomForestClassifier(random_state=42),
    "k-Nearest Neighbors": KNeighborsClassifier(),
    "Naive Bayes": GaussianNB(),
    "Support Vector Machine": SVC(kernel='linear',probability=True, random_state=42),
    "Gradient Boosting": GradientBoostingClassifier(random_state=42)
}

# Αποθήκευση αποτελεσμάτων σε DataFrame
results_df = pd.DataFrame(columns=[
    'Classifier', 'Set', 'Balanced Set', 'Training Samples', 'Non-healthy Training',
    'TP', 'TN', 'FP', 'FN', 'ROC-AUC'
])

# Εκπαίδευση των μοντέλων και υπολογισμός των μετρικών
for fold, (train_index, test_index) in enumerate(skf.split(X_scaled, y), 1):
    X_train, X_test = X_scaled[train_index], X_scaled[test_index]
    y_train, y_test = y.iloc[train_index], y.iloc[test_index]

    # Υπολογισμός της αναλογίας χρεωκοπημένων και υγιών εταιρειών στο training set
    healthy_count_train = sum(y_train == 1)
    bankrupt_count_train = sum(y_train == 2)

    # Αν η αναλογία είναι πάνω από 3:1, να γίνεται επιλογή των υγιών με τυχαίο τρόπο
    if healthy_count_train > 3 * bankrupt_count_train:
        healthy_train = X_train[y_train == 1]
        bankrupt_train = X_train[y_train == 2]
        healthy_train_resampled = resample(healthy_train, replace=False, n_samples=3*bankrupt_count_train, random_state=42)
        X_train = np.concatenate([healthy_train_resampled, bankrupt_train], axis=0)
        y_train = np.concatenate([np.ones(len(healthy_train_resampled)), np.full(len(bankrupt_train), 2)], axis=0)
        balanced = 'Balanced'
    else:
        balanced = 'Unbalanced'

    # Εκπαίδευση των μοντέλων
    for model_name, model in models.items():
        model.fit(X_train, y_train)
        y_train_pred = model.predict(X_train)
        y_test_pred = model.predict(X_test)

        # Υπολογισμός μετρικών για το training set
        cm_train = confusion_matrix(y_train, y_train_pred)
        tp_train, fp_train, fn_train, tn_train = cm_train.ravel()
        accuracy_train = accuracy_score(y_train, y_train_pred)
        precision_train = precision_score(y_train, y_train_pred, pos_label=2)
        recall_train = recall_score(y_train, y_train_pred, pos_label=2)
        f1_train = f1_score(y_train, y_train_pred, pos_label=2)
        auc_train = roc_auc_score(y_train, model.predict_proba(X_train)[:, 1])

        # Υπολογισμός μετρικών για το test set
        cm_test = confusion_matrix(y_test, y_test_pred)
        tp_test, fp_test, fn_test, tn_test = cm_test.ravel()
        accuracy_test = accuracy_score(y_test, y_test_pred)
        precision_test = precision_score(y_test, y_test_pred, pos_label=2)
        recall_test = recall_score(y_test, y_test_pred, pos_label=2)
        f1_test = f1_score(y_test, y_test_pred, pos_label=2)
        auc_test = roc_auc_score(y_test, model.predict_proba(X_test)[:, 1])

        # Εκτύπωση confusion matrix
        fig, ax = plt.subplots(1, 2, figsize=(12, 6))

        # Train confusion matrix
        sns.heatmap(cm_train, annot=True, fmt="d", cmap="Blues", ax=ax[0])
        ax[0].set_title(f"{model_name} - Train Set")
        ax[0].set_xlabel('Predicted')
        ax[0].set_ylabel('True')

        # Test confusion matrix
        sns.heatmap(cm_test, annot=True, fmt="d", cmap="Blues", ax=ax[1])
        ax[1].set_title(f"{model_name} - Test Set")
        ax[1].set_xlabel('Predicted')
        ax[1].set_ylabel('True')

        plt.show()

        # Εκτύπωση των μετρικών
        print(f"{model_name} - Fold {fold} ({balanced}):")
        print(f"Training Set: Accuracy={accuracy_train:.2f}, Precision={precision_train:.2f}, Recall={recall_train:.2f}, F1={f1_train:.2f}, ROC-AUC={auc_train:.2f}")
        print(f"Test Set: Accuracy={accuracy_test:.2f}, Precision={precision_test:.2f}, Recall={recall_test:.2f}, F1={f1_test:.2f}, ROC-AUC={auc_test:.2f}")
        print("-" * 50)

        # Καταχώρηση αποτελεσμάτων στο DataFrame
        results_df = pd.concat([results_df, pd.DataFrame([{
            'Classifier': model_name,
            'Set': 'Train',
            'Balanced Set': balanced,
            'Training Samples': len(y_train),
            'Non-healthy Training': bankrupt_count_train,
            'TP': tp_train,
            'TN': tn_train,
            'FP': fp_train,
            'FN': fn_train,
            'ROC-AUC': auc_train
        }])], ignore_index=True)

        results_df = pd.concat([results_df, pd.DataFrame([{
            'Classifier': model_name,
            'Set': 'Test',
            'Balanced Set': balanced,
            'Training Samples': len(y_test),
            'Non-healthy Training': bankrupt_count_train,
            'TP': tp_test,
            'TN': tn_test,
            'FP': fp_test,
            'FN': fn_test,
            'ROC-AUC': auc_test
        }])], ignore_index=True)


